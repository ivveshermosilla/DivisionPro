	    function refreshLanguageToggle() {
	        const btn = document.getElementById('global-lang-btn');
	        const label = appState.lang === 'es' ? 'Idioma activo: español. Cambiar a inglés.' : 'Active language: English. Switch to Spanish.';
	        if (btn) {
	            btn.dataset.activeLang = appState.lang;
	            btn.setAttribute('aria-label', label);
	        }
	        document.querySelectorAll('.js-lang-toggle').forEach(toggle => {
	            toggle.dataset.activeLang = appState.lang;
	            toggle.setAttribute('aria-label', label);
	        });
	        document.documentElement.lang = appState.lang;
	    }
